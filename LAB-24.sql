--8. CREATE A STORED PROCEDURE THAT ACCEPTS A NUMBER AS INPUT AND DISPLAYS DETAILS OF THE LAST N EMPLOYEES
--WHO JOINED THE ORGANIZATION.
CREATE OR ALTER PROCEDURE SP_LAST_N_EMPLOYEE
@N INT
