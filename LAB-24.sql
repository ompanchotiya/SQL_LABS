--13. CREATE A STORED PROCEDURE THAT ACCEPTS A PUBLISHER NAME AND DISPLAYS THE TOTAL NUMBER OF BOOKS
--PUBLISHED BY THAT PUBLISHER.

CREATE OR ALTER PROCEDURE SP_TOTAL_BOOKS_PUBLISHER
@PUBLISHERNAME VARCHAR(100)
AS
BEGIN
SELECT P.PUBLISHERNAME,COUNT(B.BOOKID) AS TOTAL_BOOKS
FROM PUBLISHER P
JOIN BOOK B ON P.PUBLISHERID=B.PUBLISHERID
WHERE P.PUBLISHERNAME=@PUBLISHERNAME
GROUP BY P.PUBLISHERNAME;
END

EXEC SP_TOTAL_BOOKS_PUBLISHER 'PENGUIN';
--14. CREATE A STORED PROCEDURE THAT ACCEPTS A PRICE RANGE (MIN PRICE MAX PRICE) AND DISPLAYS BOOKS WHOSE
--PRICES FALL WITHIN THAT RANGE.
CREATE OR ALTER PROCEDURE SP_BOOK_PRICE_RANGE
@MINPRICE DECIMAL(8,2),@MAXPRICE DECIMAL(8,2)
AS
BEGIN
SELECT * FROM BOOK
WHERE PRICE BETWEEN @MINPRICE AND @MAXPRICE;
END

